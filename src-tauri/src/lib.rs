fn verdant_root() -> Result<PathBuf, String> {
    #[cfg(target_os = "windows")]
    {
        let appdata = std::env::var("APPDATA")
            .map_err(|_| "APPDATA nao encontrado".to_string())?;
        Ok(PathBuf::from(appdata).join(".verdant"))
    }
    #[cfg(not(target_os = "windows"))]
    {
        let home = std::env::var("HOME")
            .map_err(|_| "HOME nao encontrado".to_string())?;
        Ok(PathBuf::from(home).join(".config").join("verdant-launcher"))
    }
}

#[tauri::command]
fn setup_verdant_dirs() -> Result<String, String> {
    let root = verdant_root()?;
    let subdirs = [
        "instances",
        "assets",
        "libraries",
        "versions",
        "downloads",
        "cache",
    ];

    for dir in &subdirs {
        let path = root.join(dir);
        fs::create_dir_all(&path)
            .map_err(|e| format!("Erro ao criar '{}': {}", path.display(), e))?;
    }

    println!("[Verdant] Ã¢Å“â€¦ Pastas criadas em: {}", root.display());
    Ok(format!("OK: {}", root.display()))
}

